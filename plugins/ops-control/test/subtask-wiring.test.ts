test('a second /subtask after the first one is done reuses its row and name', async ($, on) => {
  fakeFs(on)
  mock.clock(on)
  on('ui.panes', async () => ({ value: [] }))
  on('ui.render', async () => ({ type: 'Text', props: {}, children: ['engine'] }) as RenderElement)
  on('session.id', async () => ({ value: 's1' }))
  on('session.usage', async () => ({ value: { context: { window: 1000, percent: 10 } } as never }))
  on('turn.start', async (_$: unknown, e: any) => ({ turnId: e.turnId }))
  on('turn.complete', async () => ({ text: '' }) as never)
  const first = 'acount-the-files-d7b91f2d5eb71abb', second = 'alist-the-folders-0123456789abcdef'
  await $.turn.start({ text: 'count the files', turnId: 'f1', agentId: first } as never)
  await $.turn.complete({ reason: 'answer', answer: 'done', durationMs: 10, isAborted: false, turnId: 'f1', agentId: first } as never)
  await $.turn.start({ text: 'list the folders', turnId: 'f2', agentId: second } as never)
  const ui = await $.ui.mount(PANE)
  await ui.press({ key: 'tab-agents' })
  expect(await ui.find({ text: /1 running · 0 done/ })).toBeDefined()
  expect(await ui.find({ text: /list the folders/ })).toBeDefined()
  expect(await ui.find({ text: /count the files/ })).toBeUndefined()
  await ui.unmount()
})

test('a typed /subtask and its fork\'s answer are kept as a subplan, and its fork turn is no request', async ($, on) => {
  fakeFs(on)
  mock.clock(on)
  mock.store(on)
  on('ui.panes', async () => ({ value: [] }))
  on('ui.render', async () => ({ type: 'Text', props: {}, children: ['engine'] }) as RenderElement)
  on('session.id', async () => ({ value: 's1' }))
  on('session.usage', async () => ({ value: { context: { window: 1000, percent: 10 } } as never }))
  on('turn.start', async (_$: unknown, e: any) => ({ turnId: e.turnId }))
  on('turn.complete', async () => ({ text: '' }) as never)
  on('prompt.submit', async (_$: unknown, e: any) => ({ text: e.text }) as never)
  const agentId = 'ahow-is-the-d70cc6aaf61dfd43'
  await $.prompt.submit({ text: '/subtask how is XP made?', command: { name: 'subtask', args: 'how is XP made?' }, origin: { kind: 'composer' }, wait: false } as never)
  await $.turn.start({ text: 'how is XP made?', turnId: 'f1', agentId } as never)
  await $.turn.complete({ reason: 'answer', answer: 'At the end of each turn.', durationMs: 10, isAborted: false, turnId: 'f1', agentId } as never)
  const ui = await $.ui.mount(PANE)
  expect(await ui.find({ text: /SUBPLANS/ })).toBeDefined()
  expect(await ui.find({ text: /Q how is XP made\?/ })).toBeDefined()
  expect(await ui.find({ text: /A At the end of each turn\./ })).toBeDefined()
  expect(await ui.find({ text: /No requests yet/ })).toBeDefined()
  await ui.unmount()
})
